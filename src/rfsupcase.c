VOID
RfsDefaultUpcase(PUSHORT Table)
{
    ULONG i, k;
    for (i = 0; i < 65536; i++) Table[i] = (USHORT)i;
    for (i = 0; i < sizeof(Runs) / sizeof(Runs[0]); i++) {
        ULONG c = Runs[i].Start;
        for (k = 0; k < Runs[i].Count; k++, c += Runs[i].Step) Table[c] = (USHORT)(c + Runs[i].Delta);
    }
}
